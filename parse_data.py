COLORS = ['#2563eb', '#ef4444', '#10b981', '#f59e0b']

def parse_value(s, event):
    """タイムまたは距離をfloatに変換する"""
    s = s.strip()
    if not s:
        return None

    # 距離系: "9m73", "2m42cm", "2m05" など
    m = re.match(r'^(\d+)m(\d+)cm?$', s)
    if m:
        return round(int(m.group(1)) + int(m.group(2)) / 100, 2)
    m = re.match(r'^(\d+)m(\d+)$', s)
    if m:
        return round(int(m.group(1)) + int(m.group(2)) / 100, 2)

    # 分秒小数: "1分07秒27"
    m = re.match(r'^(\d+)分(\d+)秒(\d+)$', s)
    if m:
        return round(int(m.group(1)) * 60 + int(m.group(2)) + int(m.group(3)) / 100, 2)

    # 分秒: "1分07秒"
    m = re.match(r'^(\d+)分(\d+)秒$', s)
    if m:
        return round(int(m.group(1)) * 60 + int(m.group(2)), 2)

    # 秒小数: "9秒20"
    m = re.match(r'^(\d+)秒(\d+)$', s)
    if m:
        return round(int(m.group(1)) + int(m.group(2)) / 100, 2)

    # 秒のみ: "58秒"
    m = re.match(r'^(\d+)秒$', s)
    if m:
        return round(float(m.group(1)), 2)

    return None

import random, time as _time

def uid():
    return '%x%s' % (int(_time.time() * 1000), '%04x' % random.randint(0, 0xffff))

# 選手リストを構築
athlete_names = []
for line in RAW.strip().splitlines():
    parts = line.split(',')
    name = parts[0].strip()
    if name not in athlete_names:
        athlete_names.append(name)

athletes = []
for i, name in enumerate(athlete_names):
    athletes.append({'id': 'a' + str(i+1), 'name': name, 'color': COLORS[i % len(COLORS)]})

ath_map = {a['name']: a['id'] for a in athletes}

# 記録を構築
records = []
skipped = []
for line in RAW.strip().splitlines():
    parts = [p.strip() for p in line.split(',')]
    if len(parts) < 4:
        continue
    name, date_raw, event, value_raw = parts[0], parts[1], parts[2], parts[3]
    note = parts[4] if len(parts) > 4 else ''

    # 日付変換 "2025/04/26" → "2025-04-26"
    date = date_raw.replace('/', '-')

    val = parse_value(value_raw, event)
    if val is None:
        skipped.append(line)
        continue

    ath_id = ath_map.get(name)
    if not ath_id:
        skipped.append(line)
        continue

    records.append({
        'id': uid(),
        'athleteId': ath_id,
        'event': event,
        'date': date,
        'time': val,
        'note': note,
    })

result = {'athletes': athletes, 'records': records}

print(json.dumps(result, ensure_ascii=False, indent=2))
